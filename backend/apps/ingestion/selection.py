BINARY_SNIFF_BYTES = 8192


class SkipReason:
    DIRECTORY = "directory"
    FILENAME = "filename"
    PATTERN = "generated"
    EXTENSION = "binary-extension"
    GITIGNORED = "gitignored"
    TOO_LARGE = "too-large"
    BINARY_CONTENT = "binary-content"
    EMPTY = "empty"
    UNKNOWN_TYPE = "unsupported-type"


def language_for(path):
    return LANGUAGE_BY_EXTENSION.get(_extension(path), "")


def _extension(path):
    _, _, ext = posixpath.basename(path).rpartition(".")
    return f".{ext.lower()}" if ext else ""


def build_gitignore_spec(gitignore_text):
    """Compile the repository's own .gitignore into a matcher.

    A tarball contains everything that was committed, so a repository that committed
    its build output would otherwise have it indexed. Honouring .gitignore means the
    repository's own opinion about what is not source is respected.

    Uses pathspec's gitwildmatch implementation rather than a hand-rolled one:
    negations, `**`, and directory-only patterns all have real semantics that are easy
    to get subtly wrong.
    """
    if not gitignore_text:
        return None
    try:
        return pathspec.PathSpec.from_lines("gitwildmatch", gitignore_text.splitlines())
    except Exception:
        # A malformed .gitignore must not stop the whole job.
        return None


def should_skip(path, size_bytes, gitignore_spec=None):
    """Return a SkipReason, or None when the file should be indexed.

    Ordered cheapest check first: path inspection before size before reading bytes.
    """
    parts = path.split("/")
    name = parts[-1]

    if any(part in SKIP_DIRECTORIES for part in parts[:-1]):
        return SkipReason.DIRECTORY

    if name in SKIP_FILENAMES:
        return SkipReason.FILENAME

    if any(fnmatch.fnmatch(name, pattern) for pattern in SKIP_PATTERNS):
        return SkipReason.PATTERN

    if _extension(path) in SKIP_EXTENSIONS:
        return SkipReason.EXTENSION

    if gitignore_spec is not None and gitignore_spec.match_file(path):
        return SkipReason.GITIGNORED

    if size_bytes == 0:
        return SkipReason.EMPTY

    if size_bytes > settings.INGESTION_MAX_FILE_BYTES:
        return SkipReason.TOO_LARGE

    return None


def looks_binary(data):
    """A null byte in the first few KB is the classic, and reliable, binary tell."""
    return b"\x00" in data[:BINARY_SNIFF_BYTES]


def decode(data):
    """Decode file bytes to text, or return None when it is not usable text."""
    if looks_binary(data):
        return None
    for encoding in ("utf-8", "utf-8-sig", "latin-1"):
        try:
            return data.decode(encoding)
        except UnicodeDecodeError:
            continue
    return None
