"""Decide which files in a repository are worth embedding.

This is the main lever on both free tiers. Every file that gets past here costs
Gemini quota to embed and Neon storage to keep (roughly 6 KB of vector per chunk at
1536 dimensions), so the default is to skip anything that is not hand-written source.

Skipping is also a quality decision, not only a cost one: a minified bundle or a lock
file embeds into noise that pollutes retrieval results for every real query.
"""

